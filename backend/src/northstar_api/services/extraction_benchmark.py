"""Evaluate a human-adjudicated reference against canonical extraction records.

Run: python -m northstar_api.services.extraction_benchmark reference.json extracted.json
References require source_sha256, adjudicated_by and pages with numbered blocks.
No ground truth is generated by a model and no aggregate accuracy is invented.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from difflib import SequenceMatcher
from pathlib import Path
from typing import Any


def evaluate(reference: dict[str, Any], candidate: dict[str, Any]) -> dict[str, Any]:
    if not reference.get("adjudicated_by") or reference.get("source_sha256") != candidate.get(
        "source_sha256"
    ):
        raise ValueError("Benchmark requires an adjudicated reference for this exact source")
    expected = {p["number"]: p for p in reference["pages"]}
    actual = {p["number"]: p for p in candidate["pages"]}
    counts: Counter[str] = Counter()
    for number, page in expected.items():
        output = actual.get(number, {})
        text, selected = page["text"], output.get("selected_text") or ""
        counts["pages"] += 1
        counts["page_text_exact"] += int(text == selected)
        counts["reference_characters"] += len(text)
        # Explicitly label alignment errors: difflib is not minimum-edit-distance CER.
        for kind, a, b, c, d in SequenceMatcher(None, text, selected, autojunk=False).get_opcodes():
            if kind != "equal":
                counts["aligned_character_errors"] += max(b - a, d - c)
        critical = r"[-+−]?\d+(?:[.,]\d+)*|\b(?:NOT|EXCEPT|least|most|incorrect)\b|[²₂≤≥=<>]"
        counts["critical_token_sequences_exact"] += int(
            re.findall(critical, text, re.I) == re.findall(critical, selected, re.I)
        )
        by_id = {b["id"]: b for b in output.get("blocks", []) if b.get("status") != "split"}
        wanted_order = [b["id"] for b in page.get("blocks", [])]
        counts["reading_orders_exact"] += int(list(by_id) == wanted_order)
        for block in page.get("blocks", []):
            counts["reference_blocks"] += 1
            found = by_id.get(block["id"])
            counts["blocks_recalled"] += int(found is not None)
            structure = (found.get("reviewed_structure") or found.get("visual") or {}) if found else {}
            counts["block_text_exact"] += int(
                found is not None and found.get("selected_text") == block.get("text")
            )
            cells = {(c["row"], c["column"]): c for c in structure.get("cells", [])}
            for cell in block.get("cells", []):
                counts["reference_cells"] += 1
                output_cell = cells.get((cell["row"], cell["column"]), {})
                counts["table_cells_exact"] += int(
                    all(
                        output_cell.get(k, 1 if k.endswith("_span") else None)
                        == cell.get(k, 1 if k.endswith("_span") else None)
                        for k in ("text", "row_span", "column_span", "state")
                    )
                )
                counts["header_associations_exact"] += int(
                    output_cell.get("header_refs", []) == cell.get("header_refs", [])
                )
            for field, metric in [
                ("latex", "equations"),
                ("relationships", "relationships"),
                ("options", "question_options"),
            ]:
                if field in block:
                    counts["reference_" + metric] += 1
                    counts[metric + "_exact"] += int(structure.get(field) == block[field])
    return {
        "source_sha256": reference["source_sha256"],
        "adjudicated_by": reference["adjudicated_by"],
        "scope": "Only the supplied labeled reference; not a universal accuracy estimate",
        "counts": dict(counts),
        "aligned_character_error_rate": counts["aligned_character_errors"] / counts["reference_characters"]
        if counts["reference_characters"]
        else None,
        "block_recall": counts["blocks_recalled"] / counts["reference_blocks"]
        if counts["reference_blocks"]
        else None,
        "extra_source_units": sorted(set(actual) - set(expected)),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("extracted", type=Path)
    args = parser.parse_args()
    print(
        json.dumps(
            evaluate(
                json.loads(args.reference.read_text(encoding="utf-8")),
                json.loads(args.extracted.read_text(encoding="utf-8")),
            ),
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
